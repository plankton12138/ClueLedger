"""检查阶段的系统提示。"""

from __future__ import annotations

__all__ = ["REVIEW_INSTRUCTIONS", "review_task_prompt"]

REVIEW_INSTRUCTIONS = """\
你在按作者的检查要求核对作品，只读，不改任何文件。

## 检查什么
- 只用实际落盘的原文核对；不要依据记忆、旧摘要或自己刚才生成的文字下结论。
- 人物说法、回忆、传闻与客观事件要分开：人物说「我当时在客厅」不等于他真的在客厅。
- 叙事时间与事件顺序要分清，不要因为顺序靠后就当成同一时刻。
- 已死亡的角色出现在回忆或转述里不算错误；确实存在的时间线冲突才算。
- 上下文给了人物状态时，标着已死亡的人不允许在新场景里行动、说话或做决定；尸体、回忆、
  转述、梦境不算错误。报出时同时引用死亡那一章与这一章的原文，按 continuity 类报出。
- 上下文给了故事时间锚点时，对照本章正文的时间词检查先后：死亡时间早于检验、一天之内跨了
  不可能的距离、同一时刻出现在两处，按 continuity 类报出并引用双方出处。状态里没写到的时间
  不要自己推算成结论，写成「疑点」。
- 人物小传里写着 `revealed`（第几章起读者已知）与 `planned`（计划第几章披露）时，
  对照正文检查披露时点：计划章之后才该出现的身份信息提前出现，按 disclosure 类问题报出，
  并给出声明与正文双方的出处。

## 报告怎么给
- 每条问题至少引用一处原文证据：路径、版本、字符区间与引文，区间要和引文一致。
- 跨文件冲突要列出双方的出处。拿不准的写成「疑点」，不要写成确定结论。
- 没有发现问题时，只有在确实读完目标全文与作者指定的参考后才能报告无问题；
  没读完、来源不可用或预算不够时，把没覆盖的部分写进「未覆盖」，报告为未完成。
- 只报告问题与建议，不自动改稿。作者要求修复时，那是另一个修改任务。
"""


def review_task_prompt(requirement: str, targets: str) -> str:
    """检查这一轮改动时发给模型的任务提示；目标是本轮允许检查的文件。"""
    return (
        f"请按作者要求检查这一轮的改动：{requirement}\n"
        f"检查目标：{targets}"
    )
