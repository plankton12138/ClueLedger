import { expect, test } from "@playwright/test";

test("J8 V2 空故事：作者接受规划与正文，人工修改触发观察", async ({ page, request }, testInfo) => {
  await page.goto("/");
  await page.getByRole("button", { name: "变更中心", exact: true }).click();
  await page.getByText("规划与生成任务", { exact: true }).click();
  const workbench = page.getByRole("region", { name: "Agent 创作任务" });
  await workbench.getByRole("textbox", { name: "新故事名称" }).fill("J8 怀表谜案");
  await workbench.getByRole("button", { name: "新建 V2 故事" }).click();
  const projectInput = workbench.getByRole("textbox", { name: "创作项目编号" });
  await expect(projectInput).not.toHaveValue("");
  const project = await projectInput.inputValue();
  await workbench.getByRole("textbox", { name: "创作要求" }).fill("规划林岚递出怀表的一章与节拍");
  await workbench.getByRole("button", { name: "提出故事规划" }).click();
  const planner = workbench.getByRole("article", { name: "策划任务" });
  await expect(planner.getByText("等待审阅", { exact: true })).toBeVisible();
  let story = await (await request.get(`/api/v2/projects/${project}/story`)).json();
  expect(story.artifacts).toHaveLength(0);
  await planner.getByRole("button", { name: "接受候选并提交" }).click();
  await expect(planner.getByText(/正式提交/)).toBeVisible();
  await workbench.getByRole("combobox", { name: "已接受节拍" }).selectOption(`${project}:beat`);
  await workbench.getByRole("button", { name: "生成一章候选" }).click();
  const writer = workbench.getByRole("article", { name: "写作任务" });
  await expect(writer.getByText("等待审阅", { exact: true })).toBeVisible();
  await writer.getByRole("button", { name: "接受候选并提交" }).click();
  await expect(writer.getByText(/正式提交/)).toBeVisible();
  await workbench.getByText("人工修改正文并学习", { exact: true }).click();
  await workbench.getByRole("button", { name: "读取正文" }).click();
  const editor = workbench.getByRole("textbox", { name: "人工正文" });
  await expect(editor).toBeEnabled();
  await editor.fill("林岚递出怀表。\n\n他仍然信任这位协助者。");
  await workbench.getByRole("button", { name: "保存人工修改" }).click();
  const observer = workbench.getByRole("article", { name: "风格观察任务" });
  await expect(observer.getByText("任务完成", { exact: true })).toBeVisible();
  await workbench.getByRole("button", { name: "检查一致性" }).click();
  const audit = workbench.getByRole("article", { name: "审计任务" });
  await expect(audit.getByText("任务完成", { exact: true })).toBeVisible();
  await audit.getByRole("button", { name: "查看任务过程" }).click();
  await expect(workbench.getByText(/工作者已开始/)).toBeVisible();
  await workbench.getByRole("heading", { name: "从规划到一章" }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: testInfo.outputPath("agent-workflow.png"), fullPage: true });
  story = await (await request.get(`/api/v2/projects/${project}/story`)).json();
  expect(story.artifacts.some((a: { kind: string }) => a.kind === "narrative.beat")).toBeTruthy();
});
